#!/usr/bin/env node
// Generates src/lib/mcp/actions/catalog.generated.ts: every exported server action
// ("use server" modules under src/actions) as an MCP-callable entry with its
// signature, leading comment and the zod schemas its parameters reference.
//
//   node scripts/gen-mcp-actions.mjs
//
// Re-run after pulling upstream: new actions show up in MCP without hand edits.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const ACTIONS = path.join(ROOT, "src/actions");
const OUT = path.join(ROOT, "src/lib/mcp/actions/catalog.generated.ts");

// Never exposed over MCP:
// - signup/authenticate: identity comes from the MCP token, not credentials
// - createMcpToken: a token must not mint longer-lived tokens for itself
// - getOllamaBaseUrl: accepts an arbitrary userId (cross-user read)
// - mock.actions: bulk-generates/clears demo data
const EXCLUDE = new Set(["signup", "authenticate", "createMcpToken", "getOllamaBaseUrl"]);
const EXCLUDE_FILES = new Set(["mock.actions.ts"]);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".ts") ? [path.join(dir, e.name)] : [],
  );

// Balanced-paren slice starting at the "(" at index i.
function params(src, i) {
  let depth = 0;
  for (let j = i; j < src.length; j++) {
    if (src[j] === "(") depth++;
    else if (src[j] === ")" && --depth === 0) return src.slice(i + 1, j);
  }
  return "";
}

// "a: string, b?: { x: number }, c = 5" -> [{ name, type, optional }], splitting on top-level commas only.
function splitParams(signature) {
  const parts = [];
  let depth = 0, cur = "";
  for (const ch of signature) {
    if ("<({[".includes(ch)) depth++;
    if (">)}]".includes(ch)) depth--;
    if (ch === "," && depth === 0) { parts.push(cur); cur = ""; } else cur += ch;
  }
  parts.push(cur);
  return parts.map((p) => p.trim()).filter(Boolean).map((p) => {
    const m = /^([A-Za-z0-9_]+)(\??)\s*(?::\s*([\s\S]*?))?(?:\s*=\s*[\s\S]*)?$/.exec(p);
    if (!m) return { name: "arg", type: p, optional: true };
    return { name: m[1], type: (m[3] || "unknown").trim(), optional: m[2] === "?" || /=/.test(p) };
  });
}

function leadingComment(src, index) {
  const before = src.slice(0, index).split("\n");
  const lines = [];
  for (let k = before.length - 2; k >= 0; k--) {
    const l = before[k].trim();
    if (l.startsWith("//") || l.startsWith("*") || l.startsWith("/**") || l.endsWith("*/")) lines.unshift(l.replace(/^\/\/\s?|^\/\*\*\s?|^\*\/?\s?|\*\/$/g, "").trim());
    else break;
  }
  return lines.filter(Boolean).join(" ");
}

const entries = [];
const moduleImports = new Map(); // module path -> alias
const schemaImports = new Map(); // schema name -> module path

for (const file of walk(ACTIONS).sort()) {
  if (EXCLUDE_FILES.has(path.basename(file))) continue;
  const src = fs.readFileSync(file, "utf8");
  if (!/^\s*["']use server["']/.test(src)) continue;

  const rel = path.relative(ACTIONS, file).replace(/\.ts$/, "");
  const modulePath = `@/actions/${rel}`;
  const domain = rel.split("/")[0].replace(/\.actions$/, "");

  // Map imported identifiers to their module, to resolve schema references.
  const importsOf = new Map();
  for (const m of src.matchAll(/import\s*(?:type\s*)?\{([^}]+)\}\s*from\s*["']([^"']+)["']/g)) {
    for (const name of m[1].split(",").map((s) => s.replace(/^\s*type\s+/, "").split(" as ")[0].trim()).filter(Boolean)) {
      importsOf.set(name, m[2]);
    }
  }

  const re = /^export\s+(?:async\s+function\s+([A-Za-z0-9_]+)\s*(?:<[^>]*>)?\s*\(|const\s+([A-Za-z0-9_]+)\s*=\s*async\s*\()/gm;
  for (const m of src.matchAll(re)) {
    const name = m[1] || m[2];
    if (EXCLUDE.has(name)) continue;
    const open = m.index + m[0].length - 1;
    const signature = params(src, open).replace(/\s+/g, " ").trim();
    const schemas = [...new Set([...signature.matchAll(/typeof\s+([A-Za-z0-9_]+)/g)].map((x) => x[1]))]
      .filter((s) => importsOf.has(s) && importsOf.get(s).startsWith("@/models/"));
    for (const s of schemas) schemaImports.set(s, importsOf.get(s));
    if (!moduleImports.has(modulePath)) moduleImports.set(modulePath, `m${moduleImports.size}`);
    entries.push({
      key: `${domain}.${name}`,
      alias: moduleImports.get(modulePath),
      name,
      signature,
      params: splitParams(signature),
      doc: leadingComment(src, m.index).slice(0, 300),
      schemas,
    });
  }
}

const seen = new Set();
for (const e of entries) {
  if (seen.has(e.key)) e.key = `${e.key}@${e.alias}`;
  seen.add(e.key);
}

const out = [
  "// GENERATED by scripts/gen-mcp-actions.mjs — do not edit by hand.",
  "/* eslint-disable */",
  'import type { ZodTypeAny } from "zod";',
  ...[...moduleImports].map(([p, a]) => `import * as ${a} from "${p}";`),
  ...[...groupBy(schemaImports)].map(([p, names]) => `import { ${names.join(", ")} } from "${p}";`),
  "",
  "export interface McpActionEntry {",
  "  fn: (...args: any[]) => Promise<unknown> | unknown;",
  "  signature: string;",
  "  params: { name: string; type: string; optional: boolean }[];",
  "  doc: string;",
  "  schemas: Record<string, ZodTypeAny>;",
  "}",
  "",
  "export const MCP_ACTIONS: Record<string, McpActionEntry> = {",
  ...entries.map(
    (e) =>
      `  ${JSON.stringify(e.key)}: { fn: ${e.alias}.${e.name} as any, signature: ${JSON.stringify(e.signature)}, params: ${JSON.stringify(e.params)}, doc: ${JSON.stringify(e.doc)}, schemas: { ${e.schemas.join(", ")} } },`,
  ),
  "};",
  "",
].join("\n");

function groupBy(map) {
  const g = new Map();
  for (const [name, p] of map) g.set(p, [...(g.get(p) || []), name]);
  return g;
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`${entries.length} actions from ${moduleImports.size} modules, ${schemaImports.size} schemas -> ${path.relative(ROOT, OUT)}`);
